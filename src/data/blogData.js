export const STORAGE_CUSTOM_POSTS_KEY = 'tallyin_custom_blog_posts';
export const STORAGE_BLOG_VIEWS_KEY = 'tallyin_blog_views_map';

/**
 * Format integer view counts into clean human-friendly strings (e.g. 2,420 views, 10 views)
 */
export function formatViews(views) {
  const num = Number(views) || 0;
  return num.toLocaleString();
}

/**
 * Get all blog posts (built-in seed posts + custom created posts from storage)
 */
export function getStoredBlogPosts() {
  if (typeof window === 'undefined') return SEED_BLOG_POSTS;
  try {
    const raw = localStorage.getItem(STORAGE_CUSTOM_POSTS_KEY);
    const custom = raw ? JSON.parse(raw) : [];
    // Ensure all custom posts have necessary defaults
    const sanitizedCustom = Array.isArray(custom) ? custom : [];
    
    // Merge: custom posts take precedence if same ID, otherwise prepended
    const customIds = new Set(sanitizedCustom.map(p => p.id));
    const remainingSeed = SEED_BLOG_POSTS.filter(p => !customIds.has(p.id));
    return [...sanitizedCustom, ...remainingSeed];
  } catch (err) {
    console.warn('Failed to load blog posts from storage:', err);
    return SEED_BLOG_POSTS;
  }
}

/**
 * Save or update a custom blog post in storage
 */
export function saveStoredBlogPost(post) {
  if (typeof window === 'undefined' || !post) return;
  try {
    const raw = localStorage.getItem(STORAGE_CUSTOM_POSTS_KEY);
    const existing = raw ? JSON.parse(raw) : [];
    const index = existing.findIndex(p => p.id === post.id);
    let updated;
    if (index >= 0) {
      updated = [...existing];
      updated[index] = { ...existing[index], ...post, updatedAt: new Date().toISOString() };
    } else {
      updated = [post, ...existing];
    }
    localStorage.setItem(STORAGE_CUSTOM_POSTS_KEY, JSON.stringify(updated));
    return updated;
  } catch (err) {
    console.error('Failed to save blog post to storage:', err);
  }
}

/**
 * Update the approval status of a blog post
 */
export function updateBlogPostStatus(id, newStatus, reason = '') {
  if (typeof window === 'undefined' || !id) return;
  try {
    const raw = localStorage.getItem(STORAGE_CUSTOM_POSTS_KEY);
    const existing = raw ? JSON.parse(raw) : [];
    const index = existing.findIndex(p => p.id === id);
    if (index >= 0) {
      existing[index].status = newStatus;
      if (newStatus === 'published' && !existing[index].publishedAt) {
        existing[index].publishedAt = new Date().toLocaleDateString('en-US', {
          month: 'long',
          day: 'numeric',
          year: 'numeric'
        });
      }
      if (reason) existing[index].reviewReason = reason;
      existing[index].reviewedAt = new Date().toISOString();
      localStorage.setItem(STORAGE_CUSTOM_POSTS_KEY, JSON.stringify(existing));
      return existing;
    }
    return existing;
  } catch (err) {
    console.error('Failed to update blog post status:', err);
  }
}

/**
 * Delete a post from storage
 */
export function deleteStoredBlogPost(id) {
  if (typeof window === 'undefined' || !id) return;
  try {
    const raw = localStorage.getItem(STORAGE_CUSTOM_POSTS_KEY);
    const existing = raw ? JSON.parse(raw) : [];
    const filtered = existing.filter(p => p.id !== id);
    localStorage.setItem(STORAGE_CUSTOM_POSTS_KEY, JSON.stringify(filtered));
    return filtered;
  } catch (err) {
    console.error('Failed to delete blog post:', err);
  }
}

/**
 * Load the dynamic views counter map
 */
export function getStoredViewsMap() {
  if (typeof window === 'undefined') return {};
  try {
    const raw = localStorage.getItem(STORAGE_BLOG_VIEWS_KEY);
    return raw ? JSON.parse(raw) : {};
  } catch {
    return {};
  }
}

/**
 * Increment the view count of an article
 */
export function incrementArticleView(id, baseCount = 0) {
  if (typeof window === 'undefined' || !id) return baseCount;
  try {
    const viewsMap = getStoredViewsMap();
    const current = typeof viewsMap[id] === 'number' ? viewsMap[id] : baseCount;
    const next = current + 1;
    viewsMap[id] = next;
    localStorage.setItem(STORAGE_BLOG_VIEWS_KEY, JSON.stringify(viewsMap));
    return next;
  } catch (err) {
    console.warn('Failed to increment view count:', err);
    return baseCount + 1;
  }
}
